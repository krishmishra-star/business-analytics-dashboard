import PageHeader from '../components/layout/PageHeader.jsx';
import ExportMenu from '../components/layout/ExportMenu.jsx';
import { Card } from '../components/ui/Card.jsx';
import { RowBars } from '../components/charts/Charts.jsx';
import { SalesTeamCard, OpsTeamCard } from '../components/dashboard/TeamSection.jsx';
import { useScope } from '../hooks/useScope.js';
import { salesTeamRows, opsTeamRows } from '../lib/aggregate.js';

export default function Team() {
  const { cur, people } = useScope();
  const sales = salesTeamRows(cur, people).map((r) => ({ ...r, short: r.name.split(' ')[0], service: r.name }));
  const ops = opsTeamRows(cur, people).map((r) => ({ ...r, short: r.name.split(' ')[0], service: r.name }));

  return (
    <>
      <PageHeader title="Team Performance" subtitle="How each person is doing in the selected period. Use the user and department filters above to focus on one person or team." actions={<ExportMenu />} />
      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Card title="Revenue generated by salesperson" subtitle="Payments collected on deals they own"><RowBars data={sales} dataKey="revenue" kind="inr" labelWidth={64} /></Card>
        <Card title="Stages completed by operations" subtitle="Across orders assigned to them"><RowBars data={ops} dataKey="stagesDone" color="#7c3aed" labelWidth={64} /></Card>
      </div>
      <div className="mt-4 space-y-4">
        <SalesTeamCard pageSize={10} withExport />
        <OpsTeamCard pageSize={10} withExport />
      </div>
    </>
  );
}
